/**
 * Quest: The Sorcerer's Trial (Main Quest - Magic Path)
 * =======================================================
 *
 * Grand Narrative & Player Experience:
 * ------------------------------------
 * After completing "The Saint's First Step," the player has proven their connection to the divine aspects.
 * Librarian Anya, a master scholar of the arcane, approaches them. While Brother Thaddeus's path involved
 * faith and offering, Anya believes true communion with the God of Sorcery requires a practical thesis—a
 * demonstration of absolute mastery over magic's fundamental principles. It is, in essence, a final exam
 * for an Archmage.
 *
 * Anya has unearthed an ancient, dangerous rite: a trial to not just face, but to *construct and then deconstruct*
 * the Avatar of Sorcery itself. The trial is structured around the three pillars of magic: Creation,
 * Destruction, and Transmutation. This isn't a monster hunt; it's a journey of profound magical understanding
 * that will take the player across the entire known world.
 *
 * --- The Trial of Creation: Forging a New Rune ---
 * "To create is not to replicate, but to innovate," Anya explains. She tasks the player not with crafting
 * existing runes, but with creating a brand new one from a fragmented formula. She provides a "Cracked Runic Tablet"
 * detailing part of a formula for a 'Rune of Attunement'. To complete it, the player must seek two missing
 * fragments of knowledge.
 *
 * Part 1 (Travel & Lore): The first fragment is with a reclusive hermit mage, a former colleague of Anya's,
 * who lives in a hidden part of the Wyrmwood Grove. The hermit is eccentric and speaks in riddles, forcing the
 * player to decipher his clues to receive the "Fragment of Intent."
 *
 * Part 2 (Travel & Puzzle): The second fragment, the "Fragment of Shape," is not written but carved. Anya's research
 * points to an ancient monolith in the Sunbright Plains. The player must wait for a specific time of day (e.g., dawn)
 * for the light to reveal the inscription, which they must then copy.
 *
 * Part 3 (Creation & Interaction): With all fragments, the player returns to Anya. She helps them combine the knowledge,
 * but the final rune is inert. "It lacks a spark," she says. "It must be imprinted with raw, untamed power." The player
 * must take the 'Inert Rune of Attunement' to a place of raw elemental fury—the heart of a storm on the Gale-Swept Peaks
 * or a geyser in the Volcanic Steam Vents. By using the inert rune on the environment during the event (e.g., a lightning
 * strike or eruption), it becomes the 'Imprinted Rune of Attunement'. This act of will, of capturing raw power, is the true
 * test of Creation.
 *
 * --- The Trial of Destruction: Taming Chaos ---
 * "Any fool can break things," Anya scoffs. "A master controls the breaking." For this, she sends the player to her
 * foil: Zafira, the pragmatic, slightly unhinged alchemist in Fouthia. Zafira finds the entire "academic" trial hilarious.
 * "Anya wants you to learn about Destruction from her dusty books? Hah! Let's get our hands dirty."
 *
 * Zafira agrees to help, but requires rare ingredients: the claw of a mighty Wyvern and the volatile essence of Brimstone.
 * Upon the player's return, Zafira doesn't just imbue the claw. She creates a violently unstable energy core, a miniature
 * magical black hole contained in a dwarven vessel. "Here," she says with a manic grin. "It wants to explode. Your job
 * is to teach it *patience*."
 *
 * The player must take the 'Unstable Core' and temper it by exposing it to three great forces of the world, teaching it
 * what *not* to destroy:
 * 1. The Heat of Creation: Take it to the great forge in the Dwarven Outpost. The player must 'Use' it on the anvil while a
 *    dwarf is working, allowing it to absorb the intense heat without detonating.
 * 2. The Pressure of the Deep: Take it to the deepest part of the Sunken Labyrinth. The immense water pressure threatens
 *    to crush the vessel, and the player must survive down there for a time, letting the core stabilize.
 * 3. The Silence of the Void: Take it to the quietest, most magically null place possible—perhaps the heart of the Salt Flats,
 *    where the core learns stillness.
 *
 * After these trials, the player returns to Zafira. She nods, impressed. "You've tamed chaos. You understand." She performs
 * a final ritual, shaping the energy into a 'Core of Controlled Destruction'.
 *
 * --- The Trial of Transmutation: Rewriting Reality ---
 * "The final test," Anya says, her voice filled with reverence. "To change one thing into another is to rewrite a line in the
 * universe's own song." The task: transform a Runic Bar—a metal so magically dense its very nature is almost immutable—into
 * pure, magical gold.
 *
 * Anya explains that simple transmutation spells, which turn items to coin, are insufficient. Such a profound change requires an
 * alchemical paradox: extreme heat and extreme cold applied simultaneously. The player must use the 'Superheat Ore' spell, but
 * its fire must be focused through two opposing catalysts.
 *
 * Catalyst of Cold: The first is a 'Shard of True Ice', a piece of ice that never melts, found only in the deepest, most frigid
 * chamber of the Frostfang Peaks, likely guarded by a powerful ice creature. This shard is needed to shatter the runic bar's
 * inherent magical structure.
 *
 * Catalyst of Purity: The second is a cut 'Sunstone', a gem of perfect clarity and inner light, representing the sun's pure,
 * creative fire. This will guide the molten, unstructured essence of the runic bar to reform as gold. An uncut sunstone won't
 * do; it must be perfectly cut, requiring a high Crafting level.
 *
 * The ritual itself must be performed at a place of immense magical confluence: the Astral Altar at the apex of the Magus Spire.
 * There, the player must place the Runic Bar, Shard of True Ice, and Sunstone on the altar and cast the 'Superheat Ore' spell.
 * The result is a 'Bar of Transmuted Gold', a testament to their mastery over elemental forces.
 *
 * --- The Summoning & The Final Exam ---
 * With the 'Imprinted Rune of Attunement' (Creation), the 'Core of Controlled Destruction' (Destruction), and the 'Bar of
 * Transmuted Gold' (Transmutation), the player returns to Anya. She reveals the final step: take these three foci to the
 * Elemental Shrine in the Wyrmwood Grove.
 *
 * The shrine has three pedestals. As the player places each item, they don't just act as keys; they *become* the Avatar.
 * - The Rune of Attunement shatters into light, forming the Avatar's consciousness.
 * - The Core of Controlled Destruction floats to its chest, becoming its pulsating heart.
 * - The Bar of Transmuted Gold melts into liquid light, flowing and shaping itself into the Avatar's ephemeral body.
 *
 * The player has not just summoned a monster; they have *created* their final exam. The Avatar attacks with abilities reflecting
 * its components: creating short-lived duplicates (Creation), firing focused beams of destructive energy (Destruction), and a
 * special attack that temporarily transmutes the player's equipped weapon into a 'Useless Fish' (Transmutation).
 *
 * --- The Reward: A Vision of Understanding ---
 * Upon defeating the Avatar, it deconstructs back into raw energy, which flows into the player. They are not just given a reward;
 * they experience a vision. They see the "threads" of magic that make up a spell, feel their texture, and instinctively understand
 * how to weave a "counter-spell" around themselves. This epiphany manifests as the innate ability to use the "Protect from Magic" prayer.
 *
 * Returning to Anya, she is not just pleased; she is awestruck. "You have done more than pass a test," she says. "You have communed
 * with the very grammar of the universe. You are no longer just an adventurer who uses magic. You are a true Archmage." She rewards them
 * generously, acknowledging them as a peer. The trial is complete.
 */
